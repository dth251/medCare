-- 1. tblDiaChi
CREATE TABLE IF NOT EXISTS tblDiaChi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    soNha VARCHAR(50),
    toaNha VARCHAR(100),
    xomPho VARCHAR(150),
    phuongXa VARCHAR(100),
    quanHuyen VARCHAR(100),
    tinhThanh VARCHAR(100)
);

-- 2. tblThanhVien (Base User, Joined Inheritance)
CREATE TABLE IF NOT EXISTS tblThanhVien (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenDangNhap VARCHAR(50) NOT NULL UNIQUE,
    matKhau VARCHAR(255) NOT NULL,
    ho VARCHAR(50),
    tenDem VARCHAR(50),
    ten VARCHAR(50),
    ngaySinh DATE,
    email VARCHAR(100),
    soDienThoai VARCHAR(20),
    soTaiKhoan VARCHAR(50),
    tenNganHang VARCHAR(100),
    chuTaiKhoan VARCHAR(100),
    diaChiId BIGINT REFERENCES tblDiaChi(id)
);

-- 3. tblNhanVien
CREATE TABLE IF NOT EXISTS tblNhanVien (
    id BIGINT PRIMARY KEY REFERENCES tblThanhVien(id) ON DELETE CASCADE,
    viTriCongViec VARCHAR(30) NOT NULL
);

-- 4. tblPhongKham
CREATE TABLE IF NOT EXISTS tblPhongKham (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten VARCHAR(150) NOT NULL,
    soDienThoai VARCHAR(20),
    moTa TEXT,
    diaChiId BIGINT NOT NULL REFERENCES tblDiaChi(id)
);

-- 5. tblKhoa
CREATE TABLE IF NOT EXISTS tblKhoa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maKhoa VARCHAR(20) NOT NULL,
    ten VARCHAR(100) NOT NULL,
    moTa TEXT,
    phongKhamId BIGINT NOT NULL REFERENCES tblPhongKham(id),
    CONSTRAINT uq_khoa_phongkham_makhoa UNIQUE (phongKhamId, maKhoa)
);

-- 6. tblDonGiaTienCong
CREATE TABLE IF NOT EXISTS tblDonGiaTienCong (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chucDanh VARCHAR(30) NOT NULL,
    trinhDoHocVi VARCHAR(30) NOT NULL,
    donGiaCa NUMERIC(12, 2) NOT NULL,
    CONSTRAINT uq_chucdanh_trinhdo UNIQUE (chucDanh, trinhDoHocVi)
);

-- 7. tblNhanSuYTe
CREATE TABLE IF NOT EXISTS tblNhanSuYTe (
    id BIGINT PRIMARY KEY REFERENCES tblThanhVien(id) ON DELETE CASCADE,
    khoaId BIGINT NOT NULL REFERENCES tblKhoa(id),
    donGiaTienCongId BIGINT NOT NULL REFERENCES tblDonGiaTienCong(id)
);

-- 8. tblBacSi
CREATE TABLE IF NOT EXISTS tblBacSi (
    id BIGINT PRIMARY KEY REFERENCES tblNhanSuYTe(id) ON DELETE CASCADE,
    maBacSi VARCHAR(30) NOT NULL UNIQUE,
    hocVi VARCHAR(30) NOT NULL
);

-- 9. tblYTa
CREATE TABLE IF NOT EXISTS tblYTa (
    id BIGINT PRIMARY KEY REFERENCES tblNhanSuYTe(id) ON DELETE CASCADE,
    maYTa VARCHAR(30) NOT NULL UNIQUE,
    trinhDo VARCHAR(30) NOT NULL
);

-- 10. tblNamLamViec
CREATE TABLE IF NOT EXISTS tblNamLamViec (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten VARCHAR(50) NOT NULL UNIQUE,
    moTa TEXT
);

-- 11. tblTuanLamViec
CREATE TABLE IF NOT EXISTS tblTuanLamViec (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten VARCHAR(50) NOT NULL,
    moTa TEXT,
    ngayBatDau DATE NOT NULL UNIQUE,
    ngayKetThuc DATE NOT NULL,
    thoiDiemMoDangKy TIMESTAMP,
    hanDangKy TIMESTAMP,
    trangThai VARCHAR(30) NOT NULL,
    soCaToiThieu INT NOT NULL DEFAULT 8,
    soCaToiDa INT NOT NULL DEFAULT 12,
    soCaToiDaMoiNgay INT NOT NULL DEFAULT 2,
    namLamViecId BIGINT NOT NULL REFERENCES tblNamLamViec(id),
    CONSTRAINT uq_tuan_nam_ten UNIQUE (namLamViecId, ten)
);

-- 12. tblNgayTrongTuan
CREATE TABLE IF NOT EXISTS tblNgayTrongTuan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thu VARCHAR(20) NOT NULL,
    ngay DATE NOT NULL UNIQUE,
    moTa TEXT,
    tuanLamViecId BIGINT NOT NULL REFERENCES tblTuanLamViec(id)
);

-- 13. tblCaLamViec
CREATE TABLE IF NOT EXISTS tblCaLamViec (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenCa VARCHAR(50) NOT NULL,
    moTa TEXT,
    loaiCa VARCHAR(20) NOT NULL,
    gioBatDau TIME NOT NULL,
    gioKetThuc TIME NOT NULL,
    heSoLuong NUMERIC(4, 2) NOT NULL DEFAULT 1.00
);

-- 14. tblCaTrucKhoa
CREATE TABLE IF NOT EXISTS tblCaTrucKhoa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    moTa TEXT,
    dangMoCua BOOLEAN NOT NULL DEFAULT TRUE,
    khoaId BIGINT NOT NULL REFERENCES tblKhoa(id),
    ngayTrongTuanId BIGINT NOT NULL REFERENCES tblNgayTrongTuan(id),
    caLamViecId BIGINT NOT NULL REFERENCES tblCaLamViec(id),
    CONSTRAINT uq_catruckhoa UNIQUE (khoaId, ngayTrongTuanId, caLamViecId)
);

-- 15. tblPhieuDangKy (Module 1)
CREATE TABLE IF NOT EXISTS tblPhieuDangKy (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maPhieu VARCHAR(50) NOT NULL UNIQUE,
    ngayDangKy TIMESTAMP NOT NULL,
    trangThai VARCHAR(20) NOT NULL,
    tongSoCa INT NOT NULL,
    nhanSuId BIGINT NOT NULL REFERENCES tblNhanSuYTe(id),
    tuanLamViecId BIGINT NOT NULL REFERENCES tblTuanLamViec(id),
    CONSTRAINT uq_pdk_nhansu_tuan UNIQUE (nhanSuId, tuanLamViecId)
);

-- 16. tblDangKyCa
CREATE TABLE IF NOT EXISTS tblDangKyCa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ngayDangKy TIMESTAMP NOT NULL,
    trangThai VARCHAR(20) NOT NULL,
    phieuDangKyId BIGINT NOT NULL REFERENCES tblPhieuDangKy(id) ON DELETE CASCADE,
    caTrucKhoaId BIGINT NOT NULL REFERENCES tblCaTrucKhoa(id),
    CONSTRAINT uq_dangkyca UNIQUE (phieuDangKyId, caTrucKhoaId)
);

-- 17. tblBangPhanCong (Module 2)
CREATE TABLE IF NOT EXISTS tblBangPhanCong (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maBang VARCHAR(50) NOT NULL UNIQUE,
    ngayLap TIMESTAMP NOT NULL,
    ngayCongBo TIMESTAMP,
    trangThai VARCHAR(30) NOT NULL,
    khoaId BIGINT NOT NULL REFERENCES tblKhoa(id),
    tuanLamViecId BIGINT NOT NULL REFERENCES tblTuanLamViec(id),
    nguoiLapId BIGINT NOT NULL REFERENCES tblNhanVien(id),
    CONSTRAINT uq_bpc_khoa_tuan UNIQUE (khoaId, tuanLamViecId)
);

-- 18. tblPhanCongCa
CREATE TABLE IF NOT EXISTS tblPhanCongCa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vaiTro VARCHAR(30) NOT NULL,
    ghiChu TEXT,
    dieuDongNgoaiDangKy BOOLEAN NOT NULL DEFAULT FALSE,
    bangPhanCongId BIGINT NOT NULL REFERENCES tblBangPhanCong(id) ON DELETE CASCADE,
    nhanSuId BIGINT NOT NULL REFERENCES tblNhanSuYTe(id),
    caTrucKhoaId BIGINT NOT NULL REFERENCES tblCaTrucKhoa(id),
    CONSTRAINT uq_pcc_ca_vaitro UNIQUE (caTrucKhoaId, vaiTro),
    CONSTRAINT uq_pcc_ca_nhansu UNIQUE (caTrucKhoaId, nhanSuId)
);

-- 19. tblChamCong (Module 3)
CREATE TABLE IF NOT EXISTS tblChamCong (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gioCheckIn TIMESTAMP,
    gioCheckOut TIMESTAMP,
    trangThai VARCHAR(30) NOT NULL,
    ghiChu TEXT,
    phanCongCaId BIGINT NOT NULL UNIQUE REFERENCES tblPhanCongCa(id) ON DELETE CASCADE,
    phieuThanhToanId BIGINT
);

-- 20. tblDonKhieuNai
CREATE TABLE IF NOT EXISTS tblDonKhieuNai (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maDon VARCHAR(50) NOT NULL UNIQUE,
    ngayGui TIMESTAMP NOT NULL,
    noiDung TEXT NOT NULL,
    trangThai VARCHAR(30) NOT NULL,
    lyDoPhanHoi TEXT,
    ngayXuLy TIMESTAMP,
    phanCongCaId BIGINT NOT NULL REFERENCES tblPhanCongCa(id),
    nguoiXuLyId BIGINT REFERENCES tblNhanVien(id)
);

-- 21. tblMinhChungKhieuNai
CREATE TABLE IF NOT EXISTS tblMinhChungKhieuNai (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    duongDan VARCHAR(255) NOT NULL,
    donKhieuNaiId BIGINT NOT NULL REFERENCES tblDonKhieuNai(id) ON DELETE CASCADE,
    CONSTRAINT uq_minhchung UNIQUE (donKhieuNaiId, duongDan)
);

-- 22. tblBienBanDieuChinh
CREATE TABLE IF NOT EXISTS tblBienBanDieuChinh (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maBienBan VARCHAR(50) NOT NULL UNIQUE,
    ngayLap TIMESTAMP NOT NULL,
    soCaChinhDieuChinh INT NOT NULL DEFAULT 0,
    soCaNgoaiGioDieuChinh INT NOT NULL DEFAULT 0,
    donGiaCaApDung NUMERIC(12, 2) NOT NULL,
    heSoNgoaiGioApDung NUMERIC(4, 2) NOT NULL,
    phuCapBoSung NUMERIC(12, 2) NOT NULL DEFAULT 0,
    khauTru NUMERIC(12, 2) NOT NULL DEFAULT 0,
    soTienDieuChinh NUMERIC(12, 2) NOT NULL,
    lyDo TEXT NOT NULL,
    trangThai VARCHAR(30) NOT NULL,
    donKhieuNaiId BIGINT NOT NULL UNIQUE REFERENCES tblDonKhieuNai(id),
    nguoiLapId BIGINT NOT NULL REFERENCES tblNhanVien(id)
);

-- 23. tblPhieuThanhToan
CREATE TABLE IF NOT EXISTS tblPhieuThanhToan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maPhieu VARCHAR(50) NOT NULL UNIQUE,
    ngayLap TIMESTAMP NOT NULL,
    ngayThanhToan TIMESTAMP,
    hinhThucThanhToan VARCHAR(30),
    trangThai VARCHAR(30) NOT NULL,
    soCaChinhGoc INT NOT NULL,
    soCaNgoaiGioGoc INT NOT NULL,
    donGiaCaApDung NUMERIC(12, 2) NOT NULL,
    heSoNgoaiGioApDung NUMERIC(4, 2) NOT NULL,
    phuCapTrachNhiem NUMERIC(12, 2) NOT NULL DEFAULT 0,
    phuCapThuThuat NUMERIC(12, 2) NOT NULL DEFAULT 0,
    thuong NUMERIC(12, 2) NOT NULL DEFAULT 0,
    phat NUMERIC(12, 2) NOT NULL DEFAULT 0,
    tongThucLinh NUMERIC(12, 2) NOT NULL,
    soTaiKhoanNhan VARCHAR(50),
    nganHangNhan VARCHAR(100),
    chuTaiKhoanNhan VARCHAR(100),
    maGiaoDich VARCHAR(100) UNIQUE,
    minhChungNhanTien VARCHAR(255),
    nhanSuId BIGINT NOT NULL REFERENCES tblNhanSuYTe(id),
    tuanLamViecId BIGINT NOT NULL REFERENCES tblTuanLamViec(id),
    donGiaTienCongId BIGINT NOT NULL REFERENCES tblDonGiaTienCong(id),
    keToanId BIGINT NOT NULL REFERENCES tblNhanVien(id),
    bienBanDieuChinhId BIGINT UNIQUE REFERENCES tblBienBanDieuChinh(id),
    CONSTRAINT uq_ptt_nhansu_tuan UNIQUE (nhanSuId, tuanLamViecId)
);

